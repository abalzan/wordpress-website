<?php
/**
 * Site-wide, atomic, fail-closed event-cleanup run lock.
 *
 * Adapted from Conexao_Translation_Automation_Lock (the proven pattern in this
 * codebase) for the event-cleanup batch runner. The lock is a single row in
 * wp_options (option_name = 'conexao_event_cleanup_lock'), created atomically
 * via INSERT IGNORE on the UNIQUE key on option_name. Every mutation is a
 * compare-and-swap on the exact stored bytes, so a late or racing operation can
 * never act on a row it did not create.
 *
 * ## Fencing
 *
 * Each acquisition/reclaim carries a monotonically increasing `fence_token`.
 * The token is propagated into the run-state and verified before every
 * destructive event transaction. A worker whose lease expired cannot delete,
 * because its fence token is no longer the lock's current token.
 *
 * ## Row-lock fencing
 *
 * The destructive transaction (§4.3 of the design) opens with
 * `SELECT ... FOR UPDATE` on this lock row, which holds an InnoDB row lock for
 * the duration of the transaction. A concurrent reclaim attempt blocks until
 * the transaction commits or rolls back, then fails its CAS (0 rows) because
 * the holder renewed the lease in the same transaction.
 *
 * ## WordPress.com compatibility
 *
 * Needs nothing beyond the options table WordPress already requires (InnoDB).
 * No SSH, no WP-CLI, no filesystem, no persistent object cache.
 *
 * @package Conexao_Event_Importer
 */

defined( 'ABSPATH' ) || exit;

/**
 * Site-wide event-cleanup run lock.
 */
final class Conexao_Event_Cleanup_Lock {

	/**
	 * Option name. One site-wide lock.
	 *
	 * @var string
	 */
	const OPTION = 'conexao_event_cleanup_lock';

	/**
	 * Record schema version.
	 *
	 * @var int
	 */
	const SCHEMA_VERSION = 1;

	/**
	 * Default time-to-live in seconds.
	 *
	 * @var int
	 */
	const DEFAULT_TTL = 300;

	/**
	 * Upper bound accepted on a stored TTL.
	 *
	 * @var int
	 */
	const MAX_TTL = 3600;

	/**
	 * Outcome codes for acquisition.
	 *
	 * @var string
	 */
	const ACQUIRED    = 'acquired';
	const LOCKED      = 'locked';
	const RECLAIMED   = 'reclaimed_stale';
	const MALFORMED   = 'malformed';
	const UNAVAILABLE = 'unavailable';

	/**
	 * Outcome codes for release.
	 *
	 * @var string
	 */
	const RELEASED            = 'released';
	const NOT_OWNER           = 'not_owner';
	const NOT_HELD            = 'not_held';
	const UNAVAILABLE_RELEASE = 'unavailable';

	/**
	 * Try to become the single holder of the cleanup lock.
	 *
	 * Never throws and never partially succeeds: every path returns a result
	 * array whose `outcome` is one of the ACQUIRED/LOCKED/RECLAIMED/MALFORMED/
	 * UNAVAILABLE constants. `held` is the ONLY value that means "you may
	 * proceed".
	 *
	 * @param array $args {
	 *     @type string $run_id      Unique run identifier. Required.
	 *     @type int    $ttl         Lock lifetime in seconds.
	 *     @type int    $now         Clock override for deterministic tests.
	 *     @type int    $fence_token Fence token for this run (optional; generated if absent).
	 * }
	 * @return array {
	 *     @type bool   $held    True only when this run owns the lock.
	 *     @type string $outcome Outcome code.
	 *     @type string $reason  Human-readable, secret-free explanation.
	 *     @type array  $record  The lock record as stored (empty when unheld).
	 *     @type array  $event   Structured audit event.
	 * }
	 */
	public static function acquire( array $args ): array {
		// The run_id is an opaque, case-sensitive identity token: it is
		// generated by the caller (`cleanup_<random>`), stored verbatim in the
		// lock row and copied verbatim into the run-state, and the fence check
		// compares the two byte-for-byte. `sanitize_key()` LOWERCASES its
		// input, which would make the run-state copy (stored unsanitised)
		// never equal the lock-row copy (stored sanitised) — every event would
		// fail the fence check. Sanitise with a case-preserving filter instead:
		// allow only the characters a run id can legitimately contain and
		// reject anything else, so a malformed id fails closed rather than
		// being silently rewritten.
		$run_id = isset( $args['run_id'] ) ? (string) $args['run_id'] : '';
		$ttl    = isset( $args['ttl'] ) ? (int) $args['ttl'] : self::DEFAULT_TTL;
		$now    = isset( $args['now'] ) ? (int) $args['now'] : time();

		if ( '' === $run_id ) {
			return self::refusal( self::UNAVAILABLE, 'no run id was supplied' );
		}

		if ( ! preg_match( '/^[A-Za-z0-9_\-]+$/', $run_id ) ) {
			return self::refusal( self::UNAVAILABLE, 'run id contains disallowed characters' );
		}

		if ( $ttl <= 0 || $ttl > self::MAX_TTL ) {
			return self::refusal( self::UNAVAILABLE, 'refusing an out-of-range lock ttl' );
		}

		$fence_token = isset( $args['fence_token'] ) ? (int) $args['fence_token'] : wp_rand( 1, PHP_INT_MAX );

		$record = array(
			'v'           => self::SCHEMA_VERSION,
			'run_id'      => $run_id,
			'acquired_at' => $now,
			'ttl'         => $ttl,
			'fence_token' => $fence_token,
		);

		$encoded = (string) wp_json_encode( $record );

		// --- 1. The atomic create. The UNIQUE key decides the winner. ------
		$inserted = self::insert_lock( $encoded );

		if ( true === $inserted ) {
			return self::success( self::ACQUIRED, 'cleanup lock acquired', $record );
		}

		if ( null === $inserted ) {
			return self::refusal( self::UNAVAILABLE, 'lock storage is unavailable; refusing to run unlocked' );
		}

		// --- 2. The lock exists. Read it and decide, never assume. ----------
		$raw = self::read_lock();

		if ( null === $raw ) {
			return self::refusal( self::UNAVAILABLE, 'lock state could not be read; refusing to run unlocked' );
		}

		$existing = self::decode( $raw );

		if ( null === $existing ) {
			return self::refusal(
				self::MALFORMED,
				'the existing lock state is malformed; refusing to overwrite it'
			);
		}

		// --- 3. A live lock held by another run is respected, always. ------
		if ( $existing['run_id'] === $run_id ) {
			return self::success( self::ACQUIRED, 'this run already holds the cleanup lock', $existing );
		}

		$age = $now - (int) $existing['acquired_at'];

		if ( $age <= (int) $existing['ttl'] ) {
			return self::failure(
				self::LOCKED,
				sprintf(
					'another run holds the cleanup lock (age %ds of %ds)',
					max( 0, $age ),
					(int) $existing['ttl']
				),
				$existing
			);
		}

		// --- 4. Stale, and only stale: reclaim by compare-and-swap. --------
		$new_fence = (int) $existing['fence_token'] + 1;
		$new_record = array(
			'v'           => self::SCHEMA_VERSION,
			'run_id'      => $run_id,
			'acquired_at' => $now,
			'ttl'         => $ttl,
			'fence_token' => $new_fence,
		);
		$new_encoded = (string) wp_json_encode( $new_record );

		if ( true !== self::swap_lock( $raw, $new_encoded ) ) {
			return self::failure(
				self::LOCKED,
				'lost the stale-lock reclaim race; another run won it',
				$existing
			);
		}

		return array(
			'held'    => true,
			'outcome' => self::RECLAIMED,
			'reason'  => sprintf(
				'reclaimed a stale lock from run %s (age %ds exceeded ttl %ds)',
				$existing['run_id'],
				$age,
				(int) $existing['ttl']
			),
			'record'  => $new_record,
			'event'   => array(
				'outcome'         => self::RECLAIMED,
				'reason'          => sprintf( 'reclaimed stale lock from run %s after %ds', $existing['run_id'], $age ),
				'run_id'          => $run_id,
				'acquired_at'     => $now,
				'ttl'             => $ttl,
				'fence_token'     => $new_fence,
				'previous_run_id' => $existing['run_id'],
			),
		);
	}

	/**
	 * Release the lock, but only if this run is the owner.
	 *
	 * The DELETE is scoped to the exact stored bytes, so ownership is enforced
	 * by the database rather than by a read that could go stale.
	 *
	 * @param string $run_id Run identifier attempting the release.
	 * @return array {
	 *     @type bool   $released True only when this run's lock was removed.
	 *     @type string $outcome  Outcome code.
	 *     @type string $reason   Human-readable explanation.
	 * }
	 */
	public static function release( string $run_id ): array {
		global $wpdb;

		$raw = self::read_lock();

		if ( null === $raw ) {
			return array(
				'released' => false,
				'outcome'  => self::NOT_HELD,
				'reason'   => 'no lock row exists; nothing to release',
			);
		}

		$existing = self::decode( $raw );

		if ( null === $existing ) {
			return array(
				'released' => false,
				'outcome'  => self::MALFORMED,
				'reason'   => 'the lock state is malformed; refusing to release it',
			);
		}

		if ( $existing['run_id'] !== $run_id ) {
			return array(
				'released' => false,
				'outcome'  => self::NOT_OWNER,
				'reason'   => 'another run owns the lock; refusing to release it',
			);
		}

		$affected = $wpdb->query(
			$wpdb->prepare(
				"DELETE FROM {$wpdb->options} WHERE option_name = %s AND option_value = %s",
				self::OPTION,
				$raw
			)
		);

		if ( false === $affected ) {
			return array(
				'released' => false,
				'outcome'  => self::UNAVAILABLE_RELEASE,
				'reason'   => 'lock storage is unavailable; release failed',
			);
		}

		self::flush_option_cache();

		return array(
			'released' => 1 === (int) $affected,
			'outcome'  => 1 === (int) $affected ? self::RELEASED : self::NOT_OWNER,
			'reason'   => 1 === (int) $affected ? 'lock released' : 'lock was changed by another process; release failed',
		);
	}

	/**
	 * Read the current lock record (as stored bytes), or null if absent.
	 *
	 * Reads the table directly rather than through get_option() so the value
	 * is the exact stored bytes (the CAS compares against these).
	 *
	 * @return string|null
	 */
	public static function read_lock(): ?string {
		global $wpdb;

		$value = $wpdb->get_var(
			$wpdb->prepare(
				"SELECT option_value FROM {$wpdb->options} WHERE option_name = %s",
				self::OPTION
			)
		);

		return null === $value ? null : (string) $value;
	}

	/**
	 * Acquire a row lock on the lock row (SELECT ... FOR UPDATE) and return
	 * the current record. The caller must hold an open transaction; the row
	 * lock is held until that transaction commits or rolls back.
	 *
	 * Returns null if the lock row does not exist (the caller must
	 * initialise it before the destructive transaction — see the design's
	 * safeguard #1).
	 *
	 * @return array|null Decoded lock record, or null if absent.
	 */
	public static function read_lock_for_update(): ?array {
		global $wpdb;

		$raw = $wpdb->get_var(
			$wpdb->prepare(
				"SELECT option_value FROM {$wpdb->options} WHERE option_name = %s FOR UPDATE",
				self::OPTION
			)
		);

		if ( null === $raw ) {
			return null;
		}

		return self::decode( (string) $raw );
	}

	/**
	 * Renew the lock's lease inside the caller's transaction, preserving the
	 * fence token. Compare-and-swap on the exact bytes read under FOR UPDATE.
	 *
	 * MySQL's UPDATE affected-rows count is the number of rows whose value
	 * actually CHANGED (unless CLIENT_FOUND_ROWS is set): an UPDATE that
	 * writes the same bytes it read returns 0, not 1. A renewal within the
	 * same second (second-precision `acquired_at`) therefore produces
	 * identical bytes and would falsely report failure. The correct success
	 * condition is "the row is still ours and unchanged since we read it":
	 * either the CAS changed it (1 row) or it was already the value we
	 * intended to write (0 rows, bytes still match). Any other outcome
	 * (false = SQL error, or the bytes no longer match) is a failure.
	 *
	 * @param string $expected_raw Exact bytes read under FOR UPDATE.
	 * @param int    $now          New acquired_at timestamp.
	 * @return bool True when this worker still owns the lock after the call.
	 */
	public static function renew_in_transaction( string $expected_raw, int $now ): bool {
		global $wpdb;

		$existing = self::decode( $expected_raw );

		if ( null === $existing ) {
			return false;
		}

		$renewed = array(
			'v'           => self::SCHEMA_VERSION,
			'run_id'      => $existing['run_id'],
			'acquired_at' => $now,
			'ttl'         => (int) $existing['ttl'],
			'fence_token' => (int) $existing['fence_token'],
		);

		$encoded = (string) wp_json_encode( $renewed );

		$affected = $wpdb->query(
			$wpdb->prepare(
				"UPDATE {$wpdb->options} SET option_value = %s WHERE option_name = %s AND option_value = %s",
				$encoded,
				self::OPTION,
				$expected_raw
			)
		);

		if ( false === $affected ) {
			return false;
		}

		if ( 1 === (int) $affected ) {
			return true;
		}

		// 0 rows: either the value was already identical (same-second
		// renewal) or another process changed the row. Re-read to tell them
		// apart. The re-read is safe inside the transaction: if another
		// process changed the row, its value will differ from $expected_raw.
		$current = $wpdb->get_var(
			$wpdb->prepare(
				"SELECT option_value FROM {$wpdb->options} WHERE option_name = %s",
				self::OPTION
			)
		);

		return (string) $current === $expected_raw;
	}

	/**
	 * Ensure the lock row exists before a destructive transaction tries to
	 * lock it with SELECT ... FOR UPDATE. Uses INSERT IGNORE so it is safe to
	 * call repeatedly. Returns true when the row exists after the call.
	 *
	 * @return bool
	 */
	public static function ensure_row_exists(): bool {
		global $wpdb;

		$placeholder = (string) wp_json_encode(
			array(
				'v'           => self::SCHEMA_VERSION,
				'run_id'      => '',
				'acquired_at' => 0,
				'ttl'         => self::DEFAULT_TTL,
				'fence_token' => 0,
			)
		);

		$wpdb->query(
			$wpdb->prepare(
				"INSERT IGNORE INTO {$wpdb->options} ( option_name, option_value, autoload ) VALUES ( %s, %s, 'no' )",
				self::OPTION,
				$placeholder
			)
		);

		$exists = $wpdb->get_var(
			$wpdb->prepare(
				"SELECT COUNT(*) FROM {$wpdb->options} WHERE option_name = %s",
				self::OPTION
			)
		);

		return (int) $exists > 0;
	}

	/**
	 * Atomically create the lock row.
	 *
	 * @param string $encoded JSON-encoded lock record.
	 * @return bool|null True on success, false on duplicate key, null on any other failure.
	 */
	private static function insert_lock( string $encoded ) {
		global $wpdb;

		$affected = $wpdb->query(
			$wpdb->prepare(
				"INSERT IGNORE INTO {$wpdb->options} ( option_name, option_value, autoload ) VALUES ( %s, %s, 'no' )",
				self::OPTION,
				$encoded
			)
		);

		if ( false === $affected ) {
			return null;
		}

		if ( 1 !== (int) $affected ) {
			return false;
		}

		self::flush_option_cache();

		return true;
	}

	/**
	 * Compare-and-swap the lock row.
	 *
	 * @param string $expected    Exact current stored value.
	 * @param string $replacement New value.
	 * @return bool True when this call performed the swap.
	 */
	private static function swap_lock( string $expected, string $replacement ): bool {
		global $wpdb;

		$affected = $wpdb->query(
			$wpdb->prepare(
				"UPDATE {$wpdb->options} SET option_value = %s WHERE option_name = %s AND option_value = %s",
				$replacement,
				self::OPTION,
				$expected
			)
		);

		if ( false === $affected ) {
			return false;
		}

		self::flush_option_cache();

		return 1 === (int) $affected;
	}

	/**
	 * Decode a lock record. Returns null if malformed.
	 *
	 * @param string $raw JSON-encoded record.
	 * @return array|null
	 */
	public static function decode( string $raw ): ?array {
		$decoded = json_decode( $raw, true );

		if ( ! is_array( $decoded ) ) {
			return null;
		}

		foreach ( array( 'v', 'run_id', 'acquired_at', 'ttl', 'fence_token' ) as $key ) {
			if ( ! array_key_exists( $key, $decoded ) ) {
				return null;
			}
		}

		if ( (int) $decoded['v'] !== self::SCHEMA_VERSION ) {
			return null;
		}

		$ttl = (int) $decoded['ttl'];

		if ( $ttl <= 0 || $ttl > self::MAX_TTL ) {
			return null;
		}

		return array(
			'v'           => (int) $decoded['v'],
			'run_id'      => (string) $decoded['run_id'],
			'acquired_at' => (int) $decoded['acquired_at'],
			'ttl'         => $ttl,
			'fence_token' => (int) $decoded['fence_token'],
		);
	}

	/**
	 * Flush the options cache so a later get_option() does not return stale
	 * data after a direct SQL mutation (design safeguard #2).
	 */
	private static function flush_option_cache(): void {
		wp_cache_delete( self::OPTION, 'options' );
	}

	/**
	 * Build a success result.
	 *
	 * @param string $outcome Outcome code.
	 * @param string $reason  Reason.
	 * @param array  $record  Lock record.
	 * @return array
	 */
	private static function success( string $outcome, string $reason, array $record ): array {
		return array(
			'held'    => true,
			'outcome' => $outcome,
			'reason'  => $reason,
			'record'  => $record,
			'event'   => array(
				'outcome'     => $outcome,
				'reason'      => $reason,
				'run_id'      => $record['run_id'],
				'acquired_at' => $record['acquired_at'],
				'ttl'         => $record['ttl'],
				'fence_token' => $record['fence_token'],
			),
		);
	}

	/**
	 * Build a failure result.
	 *
	 * @param string $outcome  Outcome code.
	 * @param string $reason   Reason.
	 * @param array  $existing Existing lock record (empty when none).
	 * @return array
	 */
	private static function failure( string $outcome, string $reason, array $existing ): array {
		return array(
			'held'    => false,
			'outcome' => $outcome,
			'reason'  => $reason,
			'record'  => $existing,
			'event'   => array(
				'outcome' => $outcome,
				'reason'  => $reason,
			),
		);
	}

	/**
	 * Build a refusal result (storage unavailable / no run id).
	 *
	 * @param string $outcome Outcome code.
	 * @param string $reason  Reason.
	 * @return array
	 */
	private static function refusal( string $outcome, string $reason ): array {
		return array(
			'held'    => false,
			'outcome' => $outcome,
			'reason'  => $reason,
			'record'  => array(),
			'event'   => array(
				'outcome' => $outcome,
				'reason'  => $reason,
			),
		);
	}
}